const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('desktop', {
  get: () => ipcRenderer.invoke('management:get'),
  add: (name, graph, kind) => ipcRenderer.invoke('management:add', name, graph, kind),
  importGraph: (name, value) => ipcRenderer.invoke('management:import', name, value),
  extract: (id, revision, shared) => ipcRenderer.invoke('management:extract', id, revision, shared),
  save: (id, revision, graph) => ipcRenderer.invoke('management:save', id, revision, graph),
  exportGraph: (graph, id) => ipcRenderer.invoke('management:export', graph, id),
  select: id => ipcRenderer.invoke('management:select', id),
  shortcut: value => ipcRenderer.invoke('management:shortcut', value),
  startLive: id => ipcRenderer.invoke('management:live', id),
  stop: () => ipcRenderer.invoke('management:stop'),
  cancel: () => ipcRenderer.invoke('management:cancel'),
  model: (action, key) => ipcRenderer.invoke('management:model', action, key),
  press: (id, node) => ipcRenderer.invoke('management:press', id, node),
  enableSpeakers: id => ipcRenderer.invoke('management:enable-speakers', id),
  audio: () => ipcRenderer.invoke('management:audio'),
  saveWav: node => ipcRenderer.invoke('management:save-wav', node),
  onAudio: callback => ipcRenderer.on('management:audio', (_event, value) => callback(value)),
  onNodeStatus: callback => ipcRenderer.on('management:node-status', (_event, value) => callback(value)),
  onPreparation: callback => ipcRenderer.on('management:preparation', (_event, value) => callback(value)),
  onUpdate: callback => ipcRenderer.on('management:update', (_event, view) => callback(view)),
  onNavigate: callback => ipcRenderer.on('management:navigate', (_event, page) => callback(page)),
  onDisplay: callback => ipcRenderer.on('management:display', (_event, update) => callback(update)),
  onModel: callback => ipcRenderer.on('management:model', (_event, view) => callback(view)),
});
